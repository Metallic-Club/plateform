//! Reads `../api/openapi.yaml` and generates the list of operations the router must serve.
//! The spec is the source of truth (design spec D2); a missing route is a test failure, not a silent 404.

use std::{env, fmt::Write as _, fs, path::PathBuf};

use yaml_rust2::{Yaml, YamlLoader};

const METHODS: [&str; 5] = ["get", "put", "post", "delete", "patch"];

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let spec_path = manifest_dir.join("..").join("api").join("openapi.yaml");
    println!("cargo:rerun-if-changed={}", spec_path.display());

    let text = fs::read_to_string(&spec_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", spec_path.display()));
    let docs = YamlLoader::load_from_str(&text)
        .unwrap_or_else(|e| panic!("openapi.yaml is not valid YAML: {e}"));
    let doc = docs.first().expect("openapi.yaml has one document");
    let paths = doc["paths"]
        .as_hash()
        .expect("openapi.yaml has a `paths` map");

    let mut out = String::from(
        "/// Every operation in `api/openapi.yaml`, generated by build.rs.\n\
         pub const OPERATIONS: &[Operation] = &[\n",
    );
    let mut seen_ids = Vec::new();
    for (path, item) in paths {
        let path = path.as_str().expect("path keys are strings");
        for method in METHODS {
            let op = &item[method];
            if matches!(op, Yaml::BadValue) {
                continue;
            }
            let id = op["operationId"]
                .as_str()
                .unwrap_or_else(|| panic!("{} {path} has no operationId", method.to_uppercase()));
            assert!(
                !seen_ids.contains(&id.to_owned()),
                "duplicate operationId {id}"
            );
            seen_ids.push(id.to_owned());
            writeln!(
                out,
                "    Operation {{ method: \"{}\", path: \"{path}\", operation_id: \"{id}\" }},",
                method.to_uppercase()
            )
            .expect("writing to a String cannot fail");
        }
    }
    out.push_str("];\n");

    let out_path =
        PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo")).join("operations.rs");
    fs::write(&out_path, out)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}
