/** Content labels as a creator questionnaire might set them. */
function contentLabel(g: Seed): FixtureGame["contentLabel"] {
  if (g.genres.includes("horror")) return "moderate";
  if (g.genres.includes("action") || g.genres.includes("survival")) return "mild";
  return "everyone";
}

